    if (value == null) return value;
    const original = String(value), normalized = original.replace(/\s+/g, ' ').trim();
    if (Object.prototype.hasOwnProperty.call(EXACT, normalized)) {
      return original.match(/^\s*/)[0] + EXACT[normalized] + original.match(/\s*$/)[0];
    }
